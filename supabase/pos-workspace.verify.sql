begin;
create function pg_temp.assert(ok boolean,message text) returns void language plpgsql as $$ begin if not coalesce(ok,false) then raise exception 'POS check failed: %',message;end if;end $$;
insert into public.onebite_users(id,name,username,role,active) values ('11111111-1111-4111-8111-111111111111','POS test Owner','pos-test-owner','Owner',true),('22222222-2222-4222-8222-222222222222','POS test Cashier','pos-test-cashier','Cashier',true);
insert into public.onebite_credentials(user_id,pin_hash,must_change) values ('11111111-1111-4111-8111-111111111111','test-only',false),('22222222-2222-4222-8222-222222222222','test-only',false);
insert into public.onebite_sessions(token_hash,user_id,expires_at,mfa_at) values(repeat('1',64),'11111111-1111-4111-8111-111111111111',now()+interval '1 day',now()),(repeat('2',64),'22222222-2222-4222-8222-222222222222',now()+interval '1 day',null);
insert into public.onebite_role_permissions(role,permission) values('Cashier','pos.access') on conflict do nothing;
delete from public.onebite_role_permissions where role='Cashier' and permission='inventory.access';
insert into public.onebite_sites(id,name,active) values(999998,'POS Assigned',true),(999999,'POS Other',true);
insert into public.onebite_user_sites(user_id,site_id) values('22222222-2222-4222-8222-222222222222',999998);
select pg_temp.assert(not has_function_privilege('anon','public.onebite_pos_api(text,jsonb,text)','execute'),'anonymous clients cannot execute internal POS API');
select pg_temp.assert(not has_function_privilege('authenticated','public.onebite_pos_api(text,jsonb,text)','execute'),'JWT clients cannot bypass custom session checks');
set local role service_role;
do $$ declare r jsonb; begin
 r=public.onebite_pos_api('bootstrap','{}',repeat('2',64));
 perform pg_temp.assert(not r ? 'error','Cashier needs POS, not Inventory permission');
 perform pg_temp.assert(jsonb_array_length(r->'sites')=1 and r->'sites'->0->>'id'='999998','Cashier sees only assigned active sites');
 perform pg_temp.assert(r ? 'versions' and r ? 'appSettings' and r ? 'permissions','bootstrap includes dated catalog and settings');
 perform pg_temp.assert(not r ? 'users' and not r ? 'sessions' and not r ? 'credentials','bootstrap exposes no other staff credentials');
 r=public.onebite_pos_api('bootstrap','{}',repeat('1',64));
 perform pg_temp.assert(jsonb_array_length(r->'sites')>=2,'Owner sees all active sites');
 perform pg_temp.assert(public.onebite_pos_api('bootstrap','{}',repeat('f',64))->>'error'='unauthorized','unknown session denied');
 perform pg_temp.assert(public.onebite_pos_api('photo.read','{"photoPath":"arbitrary/path"}',repeat('2',64))->>'error'='forbidden','unrelated catalog photo denied');
 perform pg_temp.assert(public.onebite_pos_api('payment.record','{}',repeat('2',64))->>'error'='invalid_action','no unimplemented payments accepted');
end $$;
reset role;
delete from public.onebite_role_permissions where role='Cashier' and permission='pos.access';
set local role service_role;
select pg_temp.assert(public.onebite_pos_api('bootstrap','{}',repeat('2',64))->>'error'='forbidden','revoked module takes effect immediately');
reset role;
update public.onebite_sessions set mfa_at=null where token_hash=repeat('1',64);
set local role service_role;
select pg_temp.assert(public.onebite_pos_api('bootstrap','{}',repeat('1',64))->>'error'='mfa_required','Owner verification enforced before catalog access');
reset role;
rollback;
